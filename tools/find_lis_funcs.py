"""Functions whose address the code builds with lis + addi/ori (callbacks, comparators, thread
entries) and that the recompiler does not know: the target follows the end of other code (a
branch, a return or padding) and is not a function start in the generated mapping.

Usage: find_lis_funcs.py image.bin generated_dir out.toml
"""
import os
import re
import struct
import sys

BASE = 0x82000000
TEXT_LO, TEXT_HI = 0x82360000, 0x83376864
b = open(sys.argv[1], "rb").read()
gen = sys.argv[2]
out = sys.argv[3]
starts = set(int(m, 16) for m in re.findall(r"\{ 0x([0-9A-F]{8}), ", open(os.path.join(gen, "mk9_init.cpp")).read()))


def word(a):
    return struct.unpack_from(">I", b, a - BASE)[0]


def terminator(w):
    return w in (0x4E800020, 0x4E800420, 0) or ((w >> 26) == 18 and (w & 1) == 0)


def simm(v):
    return v - 0x10000 if v & 0x8000 else v


found = {}
for a in range(TEXT_LO, TEXT_HI - 4, 4):
    w = word(a)
    if (w >> 26) != 15 or ((w >> 16) & 31) != 0:  # lis rD,HI (addis rD,0,HI)
        continue
    rd = (w >> 21) & 31
    hi = (w & 0xFFFF) << 16
    for k in range(1, 24):
        x = word(a + 4 * k)
        op = x >> 26
        if op in (14, 24):  # addi rT,rA,SIMM / ori rA,rS,UIMM
            if op == 14:
                rt, ra, lo = (x >> 21) & 31, (x >> 16) & 31, simm(x & 0xFFFF)
            else:
                ra, rt, lo = (x >> 21) & 31, (x >> 16) & 31, x & 0xFFFF
            if ra == rd:
                t = (hi + lo) & 0xFFFFFFFF
                if TEXT_LO <= t < TEXT_HI and t % 4 == 0 and t not in starts:
                    first = word(t)
                    # a switch's jump table sits right after its bctr, built by the lis just before
                    # it, and holds addresses: not code
                    inline_table = 0 < t - a <= 0x60 or TEXT_LO <= first < TEXT_HI
                    if first != 0 and terminator(word(t - 4)) and not inline_table:
                        found.setdefault(t, a)
                if rt == rd:
                    break
            elif rt == rd:
                break
        # the lis register redefined by something else, or control flow left: stop
        if op in (16, 18, 19) or ((x >> 21) & 31) == rd and op not in (36, 37, 38, 44, 45, 47, 52, 53, 54, 55):
            if op != 14 and op != 24:
                break

with open(out, "w", newline="\n") as f:
    f.write("# Functions whose address the code builds with lis + addi/ori and that have no .pdata entry.\n")
    f.write("# Generated by tools/find_lis_funcs.py.\n")
    f.write("[functions]\n")
    for t in sorted(found):
        f.write(f"0x{t:08X} = {{}}   # built at 0x{found[t]:08X}\n")
print(f"{len(found)} functions written to {out}")
