"""Code pointers in data that are not function starts, kept only when they sit in vtable-like
runs (a neighbouring word is a code pointer too) and the previous instruction ends a function.
Writes TOML [functions] lines. Usage: code_ptrs2.py image.bin generated_dir out.toml"""
import bisect
import os
import re
import struct
import sys

BASE = 0x82000000
TEXT_LO, TEXT_HI = 0x82360000, 0x83376864
b = open(sys.argv[1], "rb").read()
gen = sys.argv[2]
out = sys.argv[3]
starts = sorted(set(int(m, 16) for m in re.findall(r"\{ 0x([0-9A-F]{8}), ", open(os.path.join(gen, "mk9_init.cpp")).read())))
start_set = set(starts)


def word(a):
    return struct.unpack_from(">I", b, a - BASE)[0]


def is_code_ptr(w):
    return TEXT_LO <= w < TEXT_HI and w % 4 == 0


def terminator(w):
    return w in (0x4E800020, 0x4E800420, 0) or ((w >> 26) == 18 and (w & 1) == 0)


# scope tables of __C_specific_handler sit at the end of .rdata, before .pdata
EH_LO, EH_HI = 0x822A0000, 0x822B3600
ranges = [(0x82000400, 0x822B3404), (0x83380000, 0x834CFCE0)]


# real function extents from .pdata (leaf thunks have none); a jump table's targets are labels
# inside one of these
PDATA_LO, PDATA_N = 0x822B3600, 0xA2500 // 8
pdata = []
for i in range(PDATA_N):
    beg, w2 = struct.unpack_from(">II", b, PDATA_LO - BASE + i * 8)
    if beg:
        pdata.append((beg, beg + ((w2 >> 8) & 0x3FFFFF) * 4))
pdata.sort()
pdata_starts = [p[0] for p in pdata]


def func_index(t):
    k = bisect.bisect_right(pdata_starts, t) - 1
    if k >= 0 and pdata[k][0] <= t < pdata[k][1]:
        return k
    return -1 - t  # outside every .pdata function: its own key


found = {}
skipped_jt = 0
for lo, hi in ranges:
    a = lo
    while a < hi:
        if not is_code_ptr(word(a)):
            a += 4
            continue
        # a run of consecutive code pointers
        run_lo = a
        while a < hi and is_code_ptr(word(a)):
            a += 4
        run = [(p, word(p)) for p in range(run_lo, a, 4)]
        if len(run) < 2 or EH_LO <= run_lo < EH_HI:
            continue
        # most entries inside one function: a jump table, its targets are labels
        counts = {}
        for _, t in run:
            counts[func_index(t)] = counts.get(func_index(t), 0) + 1
        if max(counts.values()) * 4 >= len(run) * 3:
            skipped_jt += 1
            continue
        for p, t in run:
            # a function start follows the end of the code before it (a branch, a return, padding)
            if t in start_set or word(t) == 0 or not terminator(word(t - 4)):
                continue
            found.setdefault(t, p)
print(f"skipped {skipped_jt} jump-table-like runs")

with open(out, "w", newline="\n") as f:
    f.write("# Functions only reached through vtables (adjustor thunks and other leaves without .pdata).\n")
    f.write("# Generated by tools/find_vtable_funcs.py from data words that point at code.\n")
    f.write("[functions]\n")
    for t in sorted(found):
        f.write(f"0x{t:08X} = {{}}   # vtable 0x{found[t]:08X}\n")
print(f"{len(found)} functions written to {out}")
