#!/usr/bin/env python3
"""Writes games\\mk9\\build.ninja for the player package: every translated file compiled, and mk9game.dll linked, with
only what the package has (mk9/player/README.md). Paths are relative to games\\mk9, so the folder a player unpacks into
can have any name. The list of translated files comes from this release's own codegen (mk9/generated/default)."""
import argparse
import pathlib
import re

CXXFLAGS = (
    "--target=x86_64-pc-windows-msvc -fms-compatibility-version=19.50 -march=$march -msse4.1 "
    "-O3 -DNDEBUG -std=gnu++23 -ffp-contract=off -fno-exceptions -fno-rtti -nostdlibinc "
    "-DNOMINMAX -DREX_HAS_D3D12=1 -DWIN32_LEAN_AND_MEAN "
    "-Iplayer/include -Isdk/include -Isdk/include/simde"
)

parser = argparse.ArgumentParser()
parser.add_argument("--sources", required=True, help="mk9/generated/default/sources.cmake")
parser.add_argument("--out", required=True)
args = parser.parse_args()

names = re.findall(r"\$\{CMAKE_CURRENT_LIST_DIR\}/(\S+)\.cpp", pathlib.Path(args.sources).read_text(encoding="utf-8"))
names = [n for n in names if n != "mk9_register"]  # registers the code as a guest DLL: not used by one game
if len(names) < 2:
    raise SystemExit(f"no translated files listed in {args.sources}")

text = f"""# Compiles the game's translated code into mk9game.dll: see build-game.cmd. Generated by tools/player/make_build_ninja.py.
ninja_required_version = 1.10
builddir = build
include build/march.ninja
clang = ..\\..\\toolchain\\bin\\clang.exe
lld = ..\\..\\toolchain\\bin\\lld-link.exe
cxxflags = {CXXFLAGS}
gen = project/generated/default

rule pch
  command = $clang $cxxflags -x c++-header -Xclang -emit-pch -MD -MF $out.d -o $out $in
  depfile = $out.d
  deps = gcc
  description = Preparing the game's headers

rule cxx
  command = $clang $cxxflags -include-pch build/mk9.pch -MD -MF $out.d -o $out -c $in
  depfile = $out.d
  deps = gcc
  description = Compiling $in

rule cxxstub
  command = $clang $cxxflags -MD -MF $out.d -o $out -c $in
  depfile = $out.d
  deps = gcc
  description = Compiling $in

rule link
  command = $lld @$out.rsp
  rspfile = $out.rsp
  rspfile_content = /NOLOGO /DLL /NOENTRY /NODEFAULTLIB /MACHINE:X64 /OUT:$out $in @player/game_link.rsp /WHOLEARCHIVE:player/lib/mk9.lib sdk/lib/rexruntime.lib player/lib/msvcp140.lib player/lib/vcruntime140.lib player/lib/ucrtbase.lib
  description = Linking $out

build build/mk9.pch: pch $gen/mk9_pch.h
build build/game_stub.obj: cxxstub player/game_stub.cpp
"""
objects = ["build/game_stub.obj"]
for n in names:
    text += f"build build/{n}.obj: cxx $gen/{n}.cpp | build/mk9.pch\n"
    objects.append(f"build/{n}.obj")
text += ("build build/mk9game.dll: link " + " ".join(objects) +
         " | player/game_link.rsp player/lib/mk9.lib sdk/lib/rexruntime.lib\n")
text += "default build/mk9game.dll\n"
pathlib.Path(args.out).write_text(text, encoding="utf-8", newline="\n")
print(f"{args.out}: {len(names)} files")
